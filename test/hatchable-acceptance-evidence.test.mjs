test('acceptance evidence persists the entire projection in one idempotent SQL statement',async()=>{
 const calls=[];
 const db={query:async(sql,params)=>{calls.push({sql,params});return {rows:[{
  identity_id:1,assessment_id:2,manifest_id:3,evaluation_id:4,
  baseline_task_id:5,candidate_task_id:6,baseline_receipt_id:7,candidate_receipt_id:8
 }]};}};
 const saved=await persistAcceptanceEvidence({db,objectiveId:OBJECTIVE,
  candidatePullNumber:106,fetchImpl:fixtures()});
 assert.equal(saved.ok,true);
 assert.equal(calls.length,1);
 assert.match(calls[0].sql,/independent-reviewer-attested/);
 assert.match(calls[0].sql,/independent-reviewer-assessment/);
 assert.match(calls[0].sql,/held-out-evaluation-frozen/);
 assert.match(calls[0].sql,/\(\$5::jsonb->>'frozenAt'\)::timestamptz/);
 assert.match(calls[0].sql,/held-out-evaluation-observed/);
 assert.match(calls[0].sql,/ON CONFLICT DO NOTHING/);
 assert.equal(calls[0].params.length,14);
 const assessment=JSON.parse(calls[0].params[10]);
 assert.deepEqual(assessment.dissent,[]);
 const manifest=JSON.parse(calls[0].params[4]);
 assert.equal(manifest.evidenceClass,'advisory-review-count-proxy');
 assert.equal(manifest.schema,'ultron.github-review-proxy-set.v1');
 assert.equal(manifest.setsDisjoint,false);
 const evaluation=JSON.parse(calls[0].params[12]);
 assert.equal(evaluation.evidenceClass,'advisory-review-count-proxy');
 assert.equal(evaluation.setsDisjoint,false);
 assert.equal(evaluation.independentlyObserved,false);
 assert.equal(evaluation.evaluator.kind,'advisory-proxy');
 assert.equal(evaluation.verifiedBy.kind,'github-review-proxy');
 assert.equal(evaluation.candidateFailures,null);
 assert.equal(evaluation.criticalRegressions,null);
});

test('council trust signal is granted only after a fresh external reread matches persisted claims',async()=>{
 const identity={candidatePullNumber:106,reviewerId:'github:coderabbitai[bot]:136622811',
  reviewId:800};
 const assessment={candidatePullNumber:106,reviewId:800,
  reviewer:{id:'github:coderabbitai[bot]:136622811'}};
 const evaluation={candidatePullNumber:106,baselinePullNumber:103,reviewId:800,
  freezeCommentId:700,baselineScore:1/3,candidateScore:1,
  evidenceClass:'advisory-review-count-proxy',setsDisjoint:false,
  independentlyObserved:false,evaluator:{kind:'advisory-proxy'},
  verifiedBy:{kind:'github-review-proxy'},
  candidateFailures:null,criticalRegressions:null};
 assert.deepEqual(await verifyPersistedAcceptanceEvidence({objectiveId:OBJECTIVE,
  sourceSha:MAIN,identity,assessment,evaluation,fetchImpl:fixtures()}),{
   reviewer:true,evaluation:false
  });
 assert.deepEqual(await verifyPersistedAcceptanceEvidence({objectiveId:OBJECTIVE,
  sourceSha:MAIN,identity:{...identity,reviewId:999},assessment,evaluation,
  fetchImpl:fixtures()}),{reviewer:false,evaluation:false});
 assert.deepEqual(await verifyPersistedAcceptanceEvidence({objectiveId:OBJECTIVE,
  sourceSha:MAIN,identity,assessment,evaluation:{...evaluation,setsDisjoint:true},
  fetchImpl:fixtures()}),{reviewer:false,evaluation:false});
 assert.deepEqual(await verifyPersistedAcceptanceEvidence({objectiveId:OBJECTIVE,
  sourceSha:MAIN,identity,assessment,evaluation:{...evaluation,
   evaluator:{kind:'independent-evaluator',id:identity.reviewerId}},
  fetchImpl:fixtures()}),{reviewer:false,evaluation:false});
});

