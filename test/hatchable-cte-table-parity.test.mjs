import assert from 'node:assert/strict';
import { test } from 'node:test';
import { PGlite } from '@electric-sql/pglite';

// PostgreSQL TABLE references in a WITH scope are a supported equivalent to
// reading the corresponding named CTE through FROM/JOIN. Hatchable's current
// deploy linter mistakes direct CTE names for physical tables, so production
// SQL uses the explicit TABLE form. This test exercises a transaction-like,
//// data-modifying WITH chain, not only a read-only SELECT.

function sql({ explicitTable, paused }) {
  const fromControl = explicitTable ? '(TABLE control) AS c' : 'control AS c';
  const fromMoved = explicitTable ? '(TABLE moved) AS moved' : 'moved';
  const fromReceipt = explicitTable ? '(TABLE receipt) AS receipt' : 'receipt';
  return `WITH control AS MATERIALIZED (
    SELECT ${paused ? 'true' : 'false'}::boolean AS paused
  ), moved AS (
    UPDATE cte_test_jobs AS j SET status='done'
    FROM ${fromControl}
    WHERE j.id=1 AND NOT c.paused AND j.status='queued'
    RETURNING j.id,j.status
  ), receipt AS (
    INSERT INTO cte_test_events(job_id,status)
    SELECT moved.id,moved.status FROM ${fromMoved}
    RETURNING id
  )
  SELECT moved.id,receipt.id AS receipt_id
  FROM ${fromMoved} JOIN ${fromReceipt} ON true`;
}

async function probe(options) {
  const db = new PGlite();
  try {
    await db.exec(`
      CREATE TABLE cte_test_jobs(
        id integer PRIMARY KEY,
        status text NOT NULL
      );
      CREATE TABLE cte_test_events(
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        job_id integer NOT NULL,
        status text NOT NULL
      );
      INSERT INTO cte_test_jobs(id,status) VALUES(1,'queued');
    `);
    const applied = await db.query(sql(options));
    const jobs = await db.query('SELECT id,status FROM cte_test_jobs ORDER BY id');
    const events = await db.query('SELECT id,job_id,status FROM cte_test_events ORDER BY id');
    return { returned: applied.rows, jobs: jobs.rows, events: events.rows };
  } finally {
    await db.close();
  }
}

for (const paused of [false, true]) {
  test(`explicit TABLE references preserve CTE writes and receipts (paused=${paused})`, async () => {
    const original = await probe({ explicitTable: false, paused });
    const transformed = await probe({ explicitTable: true, paused });
    assert.deepEqual(transformed, original);
    if (paused) {
      assert.equal(transformed.returned.length, 0);
      assert.equal(transformed.events.length, 0);
      assert.equal(transformed.jobs[0].status, 'queued');
    } else {
      assert.equal(transformed.returned.length, 1);
      assert.equal(transformed.events.length, 1);
      assert.equal(transformed.jobs[0].status, 'done');
    }
  });
}

test('explicit TABLE references preserve multiple dependent materialized CTE rows', async () => {
  const db = new PGlite();
  try {
    const ordinary = await db.query(
      'WITH first AS MATERIALIZED (SELECT 17 AS marker), second AS (SELECT marker+1 AS marker FROM first) SELECT p.marker,q.marker AS next FROM first p CROSS JOIN second q'
    );
    const explicit = await db.query(
      'WITH first AS MATERIALIZED (SELECT 17 AS marker), second AS (SELECT marker+1 AS marker FROM (TABLE first) AS first) SELECT p.marker,q.marker AS next FROM (TABLE first) AS p CROSS JOIN (TABLE second) AS q'
    );
    assert.deepEqual(explicit.rows, ordinary.rows);
    assert.deepEqual(explicit.rows, [{ marker: 17, next: 18 }]);
  } finally {
    await db.close();
  }
});
